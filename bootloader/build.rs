//! Generate the staged user-program list from tools/programs.list.
//!
//! The bootloader must stage exactly the programs the build produced. Keeping
//! that list in two places (a hand-written array here and the real list in
//! tools/programs.list) is what made `ls` disappear: the array had 17 names,
//! the build produced 31, so programs past the cut were never loaded and
//! `spawn_user_by_name` ran on a zeroed UserProg.
//!
//! Generating the array from the list file makes drift impossible.

use std::env;
use std::fs;
use std::path::PathBuf;

fn main() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let list_path = manifest.join("../tools/programs.list");
    println!("cargo:rerun-if-changed={}", list_path.display());

    let text = fs::read_to_string(&list_path).unwrap_or_else(|e| {
        panic!("cannot read {}: {e}", list_path.display())
    });

    let mut names: Vec<String> = Vec::new();
    for line in text.lines() {
        let line = line.trim();
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        // Each line is "<name>[ <cargo-feature>]".
        if let Some(name) = line.split_whitespace().next() {
            names.push(name.to_string());
        }
    }

    assert!(!names.is_empty(), "tools/programs.list produced no program names");

    let mut src = String::new();
    src.push_str("// Generated by build.rs from tools/programs.list. Do not edit.\n");
    src.push_str("pub const PROGRAM_NAMES: &[&str] = &[\n");
    for n in &names {
        src.push_str(&format!("    \"{n}\",\n"));
    }
    src.push_str("];\n");

    let out = PathBuf::from(env::var("OUT_DIR").unwrap()).join("program_names.rs");
    fs::write(&out, src).unwrap();
}
